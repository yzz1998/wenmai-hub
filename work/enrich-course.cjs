/* 为两章补写「节」的策展导语与章节学习目标（专题馆版的策展层，不动条目正文） */
const fs = require('fs')

const INTRO = {
  'res-basic':
    '从「资源」一词的本义讲起：自然界的物质、能量与空间怎样被纳入社会生产，广义资源又如何把人力、资本、信息一并算进来。本节的重点不是背定义，而是掌握分类的三条依据 —— 按来源、按可再生性、按用途，因为它们直接决定后面「资源会不会耗尽」的判断。',
  'res-crisis':
    '把第一节的概念推到现实压力上：人口规模与消费水平一起抬高资源需求，生态足迹与承载力给出了可比较的量尺。本节还要解释两类典型失灵 —— 不可再生资源的耗竭，以及污染与生态退化背后的外部性与公地悲剧。',
  'res-sustain':
    '从 1962 年《寂静的春天》到 2015 年联合国可持续发展目标，梳理这条思想的来路。核心是布伦特兰定义与三个原则（公平性、持续性、共同性），再落到中国的实践：21 世纪议程、生态文明建设与双碳目标、循环经济。',
  'city-urban':
    '城市不是放大版的村落，它是社会分工发展到一定程度的产物。本节从三次社会大分工讲到城市的集聚效应，再给出城市化的测度方式与诺瑟姆 S 形曲线，最后谈中国城镇化道路的特殊性与城市问题的治理。',
  'city-rural':
    '农业是人类第一次系统性改造自然，也是城乡分野的起点。本节从作物起源与哥伦布大交换讲到传统农业与农业文明，再到现代农业、绿色革命及其代价，最后落到乡村社会结构：差序格局、空心化与乡村振兴。',
  'city-industry':
    '工业化是城市化提速的真正引擎。本节从工厂制度讲起，经三次工业革命与配第—克拉克定理，说明劳动力如何在三次产业之间转移；再讨论工业化如何把城乡关系推向对立，以及二元经济与城乡融合的出路。'
}

const GOALS = {
  'hs-ch2.json': [
    '说清「资源」的内涵与外延，并能按来源、可再生性、用途三种依据给资源归类',
    '用承载力、生态足迹等概念解释当代资源环境问题的成因，识别外部性与公地悲剧',
    '复述可持续发展的定义与三个原则，并举出中国的实践路径'
  ],
  'hs-ch5.json': [
    '说明城市产生的条件与城市化的测度方式，读懂诺瑟姆 S 形曲线的三个阶段',
    '比较传统农业与现代农业的差别，解释乡村社会结构的变化与乡村振兴的着力点',
    '用配第—克拉克定理与二元经济说明工业化如何改写城乡关系'
  ]
}

for (const f of ['hs-ch2.json', 'hs-ch5.json']) {
  const p = `src/data/${f}`
  const d = JSON.parse(fs.readFileSync(p, 'utf8'))
  d.sections = d.sections.map((s) => ({ ...s, intro: INTRO[s.id] || s.intro || '' }))
  d.chapter.goals = GOALS[f]
  fs.writeFileSync(p, JSON.stringify(d, null, 2) + '\n')
  const missing = d.sections.filter((s) => !s.intro).map((s) => s.id)
  console.log(f, '节导语', d.sections.length - missing.length + '/3', '目标', d.chapter.goals.length, missing.length ? '缺:' + missing : '')
}
