/**
 * 教案评阅量表（lesson · 七维 100 分）。
 *
 * 这套维度不是照搬论文量表，而是**从教案这一体裁的结构反推**的：
 * 先列出教案里实际存在、且能独立评价的 12 个结构块，再按「每个维度必须认领至少一块、
 * 每块也必须被某维覆盖」做双向校验。所以维度与教案结构是一一对应的，
 * 评语里的每一条都能指回「哪一块写得怎么样」。
 *
 * 权重上有一个刻意的倾斜：过程与时间结构给 20 分，为七维最高。
 * 因为教案和「教学设计说明」的分水岭就在这里——一节课能不能真的上下来，
 * 取决于环节是否成对、时间是否兑现、设计意图是否解释了「为什么这样排」。
 * 反过来，规范性与可执行性只给 8 分，防止「排版漂亮、表单填满、但课不能上」拿高分。
 *
 * 另一条纪律写在 prompt 里：**只评是否自洽、是否可执行，不评教学理念**。
 * 一份自述「知识讲授」的教案，很容易被模型以「不够学生主体」扣分，
 * 那是价值观判断，不是质量判断；换个人来评可能给相反结论，量表必须排除这种不稳定。
 */

