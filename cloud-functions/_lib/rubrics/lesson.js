/** 四档区间的显示用文案（按满分比例派生，与 normalize 的 levelOf 一致） */
function bandOf(max, lo, hi) {
  return `${Math.round(max * lo)}-${hi === null ? max : Math.round(max * hi) - 1}`
}

function levelLines() {
  return DIMENSIONS.map(
    (d) =>
      `${d.key} ${d.name}（满分 ${d.max} 分，证据取自「${d.block}」）\n` +
      `  观测点：${d.points.join('；')}\n` +
      `  优秀 ${bandOf(d.max, 0.88, null)}：${d.anchors.优秀}\n` +
      `  良好 ${bandOf(d.max, 0.72, 0.88)}：${d.anchors.良好}\n` +
      `  合格 ${bandOf(d.max, 0.6, 0.72)}：${d.anchors.合格}\n` +
      `  待改进 ${bandOf(d.max, 0, 0.6)}：${d.anchors.待改进}`
  ).join('\n\n')
}

